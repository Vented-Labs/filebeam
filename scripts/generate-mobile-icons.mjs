import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const swiftName = (name) => name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

export function swiftPath(d) {
    const tokens = d.match(/[MLHVCZ]|-?\d+(?:\.\d+)?/g);
    const lines = [];
    let x = 0;
    let y = 0;
    let startX = 0;
    let startY = 0;
    const number = () => {
        const value = Number(tokens.shift());
        if (!Number.isFinite(value)) throw new Error(`Invalid path coordinate: ${d}`);
        return value;
    };
    while (tokens.length) {
        const command = tokens.shift();
        if (command === 'M' || command === 'L') {
            x = number();
            y = number();
            if (command === 'M') {
                startX = x;
                startY = y;
            }
            lines.push(
                `path.${command === 'M' ? 'move' : 'addLine'}(to: CGPoint(x: ${x}, y: ${y}))`,
            );
        } else if (command === 'H' || command === 'V') {
            if (command === 'H') x = number();
            else y = number();
            lines.push(`path.addLine(to: CGPoint(x: ${x}, y: ${y}))`);
        } else if (command === 'C') {
            const cx1 = number();
            const cy1 = number();
            const cx2 = number();
            const cy2 = number();
            x = number();
            y = number();
            lines.push(
                `path.addCurve(to: CGPoint(x: ${x}, y: ${y}), control1: CGPoint(x: ${cx1}, y: ${cy1}), control2: CGPoint(x: ${cx2}, y: ${cy2}))`,
            );
        } else if (command === 'Z') {
            lines.push('path.closeSubpath()');
            x = startX;
            y = startY;
        } else throw new Error(`Unsupported custom path command: ${command}`);
    }
    return lines;
}

export async function generateMobileIcons(icons, check) {
    // Composite each opacity layer once, matching SVG group opacity at crossings.
    icons = icons
        .filter(({ name }) => ['http-server', 'webrtc-p2p'].includes(name))
        .map((icon) => ({
            ...icon,
            paths: icon.paths.reduce((layers, path) => {
                const previous = layers.at(-1);
                if (previous?.opacity === path.opacity) previous.d += ` ${path.d}`;
                else layers.push({ ...path });
                return layers;
            }, []),
        }));
    const files = new Map();
    for (const { name, paths, description } of icons) {
        files.set(
            `mobile/android/app/src/main/res/drawable/ic_custom_${name.replaceAll('-', '_')}.xml`,
            `<!-- ${description} Generated by scripts/generate-icons.mjs. Do not edit. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n${paths.map(({ d, opacity }) => `    <path android:pathData="${d}" android:strokeColor="#000000" android:strokeWidth="1.5" android:strokeLineCap="round" android:strokeLineJoin="round" android:strokeAlpha="${opacity}"/>`).join('\n')}\n</vector>\n`,
        );
    }
    const cases = icons
        .map(
            ({ name, paths, description }) =>
                `        // ${description}\n        case .${swiftName(name)}:\n            return [\n${paths
                    .map(
                        ({ d, opacity }) =>
                            `                (Path { path in\n${swiftPath(d)
                                .map((line) => `                    ${line}`)
                                .join('\n')}\n                }, ${opacity}),`,
                    )
                    .join('\n')}\n            ]`,
        )
        .join('\n');
    files.set(
        'mobile/ios/DesignSystem/CustomIcons.generated.swift',
        `// Generated by scripts/generate-icons.mjs. Do not edit.\n// Original Filebeam artwork; not Iconsax artwork.\nimport SwiftUI\n\nenum ApprovedCustomIcon: String, CaseIterable {\n${icons.map(({ name }) => `    case ${swiftName(name)} = "${name}"`).join('\n')}\n\n    var paths: [(Path, Double)] {\n        switch self {\n${cases}\n        }\n    }\n}\n\nstruct CustomIcon: View {\n    let icon: ApprovedCustomIcon\n    var size: CGFloat = 20\n\n    var body: some View {\n        let paths = icon.paths\n        GeometryReader { geometry in\n            let scale = min(geometry.size.width, geometry.size.height) / 24\n            ZStack {\n                ForEach(paths.indices, id: \\.self) { index in\n                    paths[index].0\n                        .applying(CGAffineTransform(scaleX: scale, y: scale))\n                        .stroke(style: StrokeStyle(lineWidth: 1.5 * scale, lineCap: .round, lineJoin: .round))\n                        .opacity(paths[index].1)\n                }\n            }\n        }\n        .frame(width: size, height: size)\n        .accessibilityHidden(true)\n    }\n}\n`,
    );
    for (const [path, contents] of files) {
        const target = new URL(path, root);
        if (check) {
            if ((await readFile(target, 'utf8')) !== contents)
                throw new Error(`${path} is stale. Run npm run generate:icons.`);
        } else await writeFile(target, contents);
    }
}
